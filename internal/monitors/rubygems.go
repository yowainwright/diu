func NewRubyGemsMonitor() Monitor {
	return &RubyGemsMonitor{BaseMonitor: NewBaseMonitor(core.ToolGem)}
}

func (m *RubyGemsMonitor) Initialize(config *core.Config) error {
	for _, name := range []string{"ruby", "gem"} {
		if _, err := exec.LookPath(name); err != nil {
			return fmt.Errorf("%s not found: %w", name, err)
		}
	}
	return m.BaseMonitor.Initialize(config)
}

func (m *RubyGemsMonitor) ParseCommand(cmd string, args []string) (*core.ExecutionRecord, error) {
	return newExecutionRecord(core.ToolGem, cmd, args), nil
}

//nolint:legibility // Monitor interface requires this method name.
func (m *RubyGemsMonitor) GetInstalledPackages() ([]*core.PackageInfo, error) {
	snapshot, err := readRubyGemsSnapshot()
	if err != nil {
		return nil, err
	}
	var packages []*core.PackageInfo
	for _, gem := range snapshot.Packages {
		isCLI := len(gem.Executables) > 0
		if isCLI {
			packages = append(packages, rubyGemsPackageInfo(gem))
		}
	}
	return packages, nil
}

func rubyGemsPackageInfo(gem rubyGemPackage) *core.PackageInfo {
	return &core.PackageInfo{Name: gem.Name, Version: gem.Version, Tool: core.ToolGem, Path: gem.Path}
}

func VerifyRubyGemsRemoval(pkg *core.PackageInfo) error {
	snapshot, err := readRubyGemsSnapshot()
	if err != nil {
		return err
	}
	for _, gem := range snapshot.Packages {
		hasIdentity := gem.Name == pkg.Name && gem.Version == pkg.Version
		isInstalled := hasIdentity && gem.Path == pkg.Path
		if !isInstalled {
			continue
		}
		if *gem.IsDefault {
			return fmt.Errorf("cannot uninstall default gem %s", pkg.Name)
		}
		return nil
	}
	return fmt.Errorf("gem %s changed since the last scan; run diu scan", pkg.Name)
}

func RubyGemsExecutables() (map[string]*core.PackageInfo, error) {
	snapshot, err := readRubyGemsSnapshot()
	if err != nil {
		return nil, err
	}
	binaries := make(map[string]*core.PackageInfo)
	for _, gem := range snapshot.Packages {
		addRubyGemExecutables(binaries, gem, snapshot.Ruby)
	}
	return binaries, nil
}

func addRubyGemExecutables(binaries map[string]*core.PackageInfo, gem rubyGemPackage, ruby string) {
	for _, command := range gem.Executables {
		addRubyGemExecutable(binaries, gem, command, ruby)
	}
}

func addRubyGemExecutable(binaries map[string]*core.PackageInfo, gem rubyGemPackage, command rubyGemExecutable, ruby string) {
	active, err := exec.LookPath(command.Name)
	if err != nil {
		return
	}
	isOwned := rubyGemsSameFile(active, command.Path) || rubyGemsWrapperMatches(active, gem, command, ruby)
	if !isOwned {
		return
	}
	pkg := rubyGemsPackageInfo(gem)
	pkg.Path = active
	binaries[command.Name] = pkg
}

func rubyGemsWrapperMatches(path string, gem rubyGemPackage, command rubyGemExecutable, ruby string) bool {
	content, err := readRubyGemsWrapper(path)
	if err != nil {
		return false
	}
	first, _, _ := strings.Cut(string(content), "\n")
	isRuby := rubyGemsWrapperUsesRuby(first, ruby)
	isGenerated := strings.Contains(string(content), "# This file was generated by RubyGems.")
	isWrapper := isRuby && isGenerated
	if !isWrapper {
		return false
	}
	pattern := fmt.Sprintf(`(?m)^[\t ]*(?:load )?Gem\.(?:activate_bin_path|activate_and_load_bin_path|bin_path)\(['"]%s['"],\s*['"]%s['"],`, regexp.QuoteMeta(gem.Name), regexp.QuoteMeta(command.Name))
	matches, _ := regexp.Match(pattern, content)
	return matches
}

func rubyGemsWrapperUsesRuby(first, ruby string) bool {
	line, isShebang := strings.CutPrefix(first, "#!")
	fields := strings.Fields(line)
	valid := isShebang && len(fields) > 0
	if !valid {
		return false
	}
	interpreter := fields[0]
	isEnv := interpreter == "/usr/bin/env" || interpreter == "/bin/env"
	if isEnv {
		if len(fields) < 2 {
			return false
		}
		interpreter, _ = exec.LookPath(fields[1])
	}
	return rubyGemsSameFile(interpreter, ruby)
}

func readRubyGemsWrapper(path string) ([]byte, error) {
	path, err := filepath.EvalSymlinks(path)
	if err != nil {
		return nil, err
	}
	directory, err := os.OpenRoot(filepath.Dir(path))
	if err != nil {
		return nil, err
	}
	defer func() { _ = directory.Close() }()
	file, err := directory.Open(filepath.Base(path))
	if err != nil {
		return nil, err
	}
	defer func() { _ = file.Close() }()
	return io.ReadAll(io.LimitReader(file, 64*1024))
}

func readRubyGemsSnapshot() (*rubyGemsSnapshot, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	output, err := exec.CommandContext(ctx, "ruby", "-rrubygems", "-rjson", "-e", rubyGemsInventoryScript).Output()
	if err != nil {
		return nil, globalPackageListError(core.ToolGem, err)
	}
	snapshot, err := parseRubyGemsSnapshot(output)
	if err != nil {
		return nil, err
	}
	if err := verifyRubyGemsRuntime(ctx, snapshot.Ruby); err != nil {
		return nil, err
	}
	return snapshot, nil
}

func parseRubyGemsSnapshot(output []byte) (*rubyGemsSnapshot, error) {
	var snapshot rubyGemsSnapshot
	if err := json.Unmarshal(output, &snapshot); err != nil {
		return nil, fmt.Errorf("invalid RubyGems inventory: %w", err)
	}
	valid := snapshot.Schema == 1 && snapshot.Packages != nil
	if !valid {
		return nil, fmt.Errorf("invalid RubyGems inventory schema")
	}
	seen := make(map[string]bool)
	for _, gem := range snapshot.Packages {
		if err := validateRubyGem(gem, seen); err != nil {
			return nil, err
		}
		seen[gem.Name] = true
	}
	return &snapshot, nil
}

func verifyRubyGemsRuntime(ctx context.Context, ruby string) error {
	output, err := exec.CommandContext(ctx, "gem", "environment").Output()
	if err != nil {
		return globalPackageListError(core.ToolGem, err)
	}
	for _, line := range strings.Split(string(output), "\n") {
		path, found := strings.CutPrefix(strings.TrimSpace(line), "- RUBY EXECUTABLE: ")
		if !found {
			continue
		}
		if rubyGemsSameFile(path, ruby) {
			return nil
		}
	}
	return fmt.Errorf("ruby and gem do not identify the same Ruby environment")
}

func rubyGemsSameFile(first, second string) bool {
	firstInfo, firstErr := os.Stat(first)
	secondInfo, secondErr := os.Stat(second)
	hasBothFiles := firstErr == nil && secondErr == nil
	if !hasBothFiles {
		return false
	}
	return os.SameFile(firstInfo, secondInfo)
}

func validateRubyGem(gem rubyGemPackage, seen map[string]bool) error {
	validName, _ := regexp.MatchString(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`, gem.Name)
	validVersion, _ := regexp.MatchString(`^[0-9][A-Za-z0-9.]*$`, gem.Version)
	validIdentity := validName && validVersion && !seen[gem.Name]
	validPackage := validIdentity && gem.IsDefault != nil
	if !validPackage {
		return fmt.Errorf("invalid RubyGems identity: %q", gem.Name)
	}
	if !validRubyGemLocation(gem) {
		return fmt.Errorf("invalid RubyGems location for %q", gem.Name)
	}
	for _, command := range gem.Executables {
		if !validRubyGemExecutable(gem.Path, command) {
			return fmt.Errorf("invalid RubyGems executable for %q", gem.Name)
		}
	}
	return nil
}

func validRubyGemLocation(gem rubyGemPackage) bool {
	platform, _ := regexp.MatchString(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`, gem.Platform)
	fullName := gem.Name + "-" + gem.Version
	if gem.Platform != "ruby" {
		fullName += "-" + gem.Platform
	}
	validRoot := filepath.IsAbs(gem.Root) && filepath.Clean(gem.Root) == gem.Root
	validPath := gem.Path == filepath.Join(gem.Root, "gems", fullName)
	isLocated := platform && validRoot && validPath
	return isLocated
}

func validRubyGemExecutable(root string, command rubyGemExecutable) bool {
	validName, _ := regexp.MatchString(`^[A-Za-z0-9][A-Za-z0-9_.+-]*$`, command.Name)
	validPath := filepath.IsAbs(command.Path) && filepath.Clean(command.Path) == command.Path
	insideGem := strings.HasPrefix(command.Path, root+string(filepath.Separator))
	matchingName := filepath.Base(command.Path) == command.Name
	isOwned := validName && validPath && insideGem && matchingName
	return isOwned
}

const rubyGemsInventoryScript = `
Gem.use_paths Gem.configuration[:gemhome], Gem.configuration[:gempath]
def exposed_source?(spec, command)
  active = ENV.fetch("PATH", "").split(File::PATH_SEPARATOR).map do |directory|
    File.expand_path(command, directory)
  end.find { |path| File.file?(path) && File.executable?(path) }
  active && File.identical?(active, spec.bin_file(command))
end
packages = Gem::Specification.map(&:name).uniq.sort.map do |name|
  candidates = Gem::Specification.find_all_by_name(name, Gem::Requirement.default_prerelease)
  spec = candidates.find do |candidate|
    candidate.executables.any? { |command| exposed_source?(candidate, command) }
  end || Gem::Specification.find_by_name(name, Gem::Requirement.default_prerelease)
  next if spec.executables.empty?
  commands = spec.executables.sort.map do |command|
    path = Gem.bin_path(name, command, Gem::Requirement.default_prerelease)
    source = spec.bin_file(command)
    next unless exposed_source?(spec, command) || File.expand_path(path) == File.expand_path(source)
    {name: command, path: File.expand_path(source)}
  end.compact
  {name: name, version: spec.version.to_s, root: File.expand_path(spec.base_dir),
   path: File.expand_path(spec.full_gem_path), platform: spec.platform.to_s,
   default: spec.default_gem?, executables: commands}
end.compact
puts JSON.generate({schema: 1, ruby: Gem.ruby, packages: packages})
`
