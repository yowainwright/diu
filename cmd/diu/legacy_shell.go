package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/user"
	"path/filepath"
	"strings"
	"syscall"

	"github.com/yowainwright/diu/internal/core"
	"github.com/yowainwright/diu/internal/safefs"
)

const (
	legacyWrapperDirName = ".local/bin/diu-wrappers"
	legacyWrapperMarker  = "# Generated by DIU"
	legacyShellPathMark  = "# DIU path configuration"
)

type legacyShellArtifacts struct {
	homeDir     string
	wrapperDirs []legacyWrapperDir
}

type legacyWrapperDir struct {
	sourcePath string
	resolved   string
}

type legacyWrapperConfig struct {
	Monitoring struct {
		Process struct {
			WrapperDir string `json:"wrapper_dir"`
		} `json:"process"`
	} `json:"monitoring"`
}

func loadLegacyShellArtifacts() (legacyShellArtifacts, error) {
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return legacyShellArtifacts{}, err
	}
	defaultDir := filepath.Join(homeDir, legacyWrapperDirName)
	paths, err := legacyWrapperPaths(homeDir, defaultDir)
	if err != nil {
		return legacyShellArtifacts{}, err
	}
	return legacyShellArtifacts{homeDir: homeDir, wrapperDirs: paths}, nil
}

func legacyWrapperPaths(homeDir, defaultDir string) ([]legacyWrapperDir, error) {
	configuredDir, err := readConfiguredLegacyWrapperDir(homeDir)
	if err != nil {
		return nil, err
	}
	paths := []string{defaultDir}
	hasCustomWrapperDir := configuredDir != "" && configuredDir != defaultDir
	if hasCustomWrapperDir {
		paths = append(paths, configuredDir)
	}
	resolved := make([]legacyWrapperDir, 0, len(paths))
	for _, path := range paths {
		directory, err := validateLegacyWrapperDir(path, homeDir)
		if err != nil {
			return nil, err
		}
		resolved = append(resolved, legacyWrapperDir{sourcePath: path, resolved: directory})
	}
	return resolved, nil
}

func readConfiguredLegacyWrapperDir(homeDir string) (string, error) {
	path := filepath.Join(homeDir, ".config", "diu", "config.json")
	contents, err := safefs.ReadFile(path)
	if os.IsNotExist(err) {
		return "", nil
	}
	if err != nil {
		return "", fmt.Errorf("failed to read legacy wrapper config: %w", err)
	}
	return parseLegacyWrapperConfig(contents)
}

func parseLegacyWrapperConfig(contents []byte) (string, error) {
	var config legacyWrapperConfig
	if err := json.Unmarshal(contents, &config); err != nil {
		return "", nil
	}
	return config.Monitoring.Process.WrapperDir, nil
}

func validateLegacyWrapperDir(path, homeDir string) (string, error) {
	if !filepath.IsAbs(path) {
		return "", fmt.Errorf("legacy wrapper directory must be absolute: %s", path)
	}
	resolved, err := resolveLegacyPath(path)
	if err != nil {
		return "", fmt.Errorf("failed to resolve legacy wrapper directory: %w", err)
	}
	if filepath.Dir(resolved) == resolved {
		return "", fmt.Errorf("legacy wrapper directory cannot be a filesystem root")
	}
	if err := validateLegacyWrapperOwnership(resolved, homeDir); err != nil {
		return "", err
	}
	return resolved, nil
}

func validateLegacyWrapperOwnership(path, homeDir string) error {
	info, err := os.Stat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("failed to inspect legacy wrapper directory: %w", err)
	}
	if !info.IsDir() {
		return fmt.Errorf("legacy wrapper path is not a directory: %s", path)
	}
	return validateLegacyWrapperLocation(path, homeDir, info)
}

func validateLegacyWrapperLocation(path, homeDir string, info os.FileInfo) error {
	resolvedHome, err := resolveLegacyPath(homeDir)
	if err != nil {
		return fmt.Errorf("failed to resolve home directory: %w", err)
	}
	withinHome, err := legacyPathWithin(resolvedHome, path)
	if err != nil {
		return err
	}
	if withinHome {
		return nil
	}
	return validateLegacyWrapperOwner(path, info)
}

func validateLegacyWrapperOwner(path string, info os.FileInfo) error {
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return fmt.Errorf("failed to inspect legacy wrapper directory owner: %s", path)
	}
	currentUser, err := user.Current()
	if err != nil {
		return fmt.Errorf("failed to find current user: %w", err)
	}
	if fmt.Sprint(stat.Uid) != currentUser.Uid {
		return fmt.Errorf("legacy wrapper directory is not owned by the current user: %s", path)
	}
	return nil
}

func legacyPathWithin(parent, child string) (bool, error) {
	relative, err := filepath.Rel(parent, child)
	if err != nil {
		return false, fmt.Errorf("failed to compare legacy wrapper paths: %w", err)
	}
	withinHome := isLegacyPathWithin(relative)
	return withinHome, nil
}

func isLegacyPathWithin(relative string) bool {
	isParent := relative == ".."
	hasParentPrefix := strings.HasPrefix(relative, ".."+string(filepath.Separator))
	isOutsideHome := isParent
	if hasParentPrefix {
		isOutsideHome = true
	}
	return !isOutsideHome
}

func resolveLegacyPath(path string) (string, error) {
	absolute, err := filepath.Abs(filepath.Clean(path))
	if err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(absolute)
	if os.IsNotExist(err) {
		parent, parentErr := resolveLegacyPath(filepath.Dir(absolute))
		if parentErr != nil {
			return "", parentErr
		}
		return filepath.Join(parent, filepath.Base(absolute)), nil
	}
	return resolved, err
}

func removeLegacyShellArtifacts(artifacts legacyShellArtifacts) error {
	var cleanupErr error
	for _, directory := range artifacts.wrapperDirs {
		cleanupErr = errors.Join(cleanupErr, removeLegacyGeneratedWrappers(directory.resolved))
		cleanupErr = errors.Join(cleanupErr, removeLegacyShellPathEntries(artifacts.homeDir, directory.sourcePath))
	}
	return cleanupErr
}

func removeLegacyGeneratedWrappers(directory string) error {
	entries, err := os.ReadDir(directory)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("failed to read legacy wrapper directory: %w", err)
	}
	var cleanupErr error
	for _, entry := range entries {
		cleanupErr = errors.Join(cleanupErr, removeLegacyGeneratedWrapper(directory, entry))
	}
	return cleanupErr
}

func removeLegacyGeneratedWrapper(directory string, entry os.DirEntry) error {
	if !entry.Type().IsRegular() {
		return nil
	}
	path := filepath.Join(directory, entry.Name())
	contents, err := safefs.ReadFile(path)
	if err != nil {
		return fmt.Errorf("failed to read legacy wrapper %s: %w", entry.Name(), err)
	}
	if !isLegacyGeneratedWrapper(string(contents)) {
		return nil
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("failed to remove legacy wrapper %s: %w", entry.Name(), err)
	}
	return nil
}

func isLegacyGeneratedWrapper(contents string) bool {
	if !strings.HasPrefix(contents, "#!/bin/bash\n"+legacyWrapperMarker+"\n") {
		return false
	}
	fields := []string{`DIU_BINARY="diu"`, "DIU_SOCKET=", "DIU_TOOL="}
	if !containsLegacyFields(contents, fields) {
		return false
	}
	return strings.Contains(contents, "ORIGINAL_BINARY=") || strings.Contains(contents, "ORIGINAL=")
}

func containsLegacyFields(contents string, fields []string) bool {
	for _, field := range fields {
		if !strings.Contains(contents, field) {
			return false
		}
	}
	return true
}

func removeLegacyShellPathEntries(homeDir, wrapperDir string) error {
	posixLine := fmt.Sprintf(`export PATH="%s:$PATH"`, core.ShellEscapeString(wrapperDir))
	fishPath := legacyFishPathLine(wrapperDir)
	entries := []struct {
		path  string
		lines []string
	}{
		{filepath.Join(homeDir, ".bashrc"), []string{posixLine}},
		{filepath.Join(homeDir, ".zshrc"), []string{posixLine}},
		{filepath.Join(homeDir, ".config", "fish", "config.fish"), []string{fishPath, strings.ReplaceAll(fishPath, "`", "\\`")}},
	}
	var cleanupErr error
	for _, entry := range entries {
		cleanupErr = errors.Join(cleanupErr, removeLegacyShellPathBlocks(entry.path, entry.lines))
	}
	return cleanupErr
}

func legacyFishPathLine(wrapperDir string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`)
	quoted := replacer.Replace(wrapperDir)
	return fmt.Sprintf("if not contains \"%s\" $PATH\n    set -gx PATH \"%s\" $PATH\nend", quoted, quoted)
}

func removeLegacyShellPathBlocks(path string, lines []string) error {
	contents, err := readShellConfigIfPresent(path)
	if err != nil {
		return err
	}
	updated := string(contents)
	for _, line := range lines {
		updated = removeLegacyShellPathBlock(updated, line)
	}
	if updated == string(contents) {
		return nil
	}
	return writeShellConfig(path, []byte(updated))
}

func removeLegacyShellPathBlock(contents, line string) string {
	block := legacyShellPathMark + "\n" + line + "\n"
	for {
		index := strings.Index(contents, block)
		if index < 0 {
			return contents
		}
		start := shellBlockStart(contents, index)
		contents = joinShellConfig(contents[:start], contents[index+len(block):])
	}
}
