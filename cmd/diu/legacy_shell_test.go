package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

type legacyShellTestFixture struct {
	homeDir            string
	defaultDir         string
	customDir          string
	oldToolPath        string
	customToolPath     string
	personalScript     string
	personalScriptPath string
}

func TestRemoveLegacyShellArtifactsRemovesWrappersAndPathBlocks(t *testing.T) {
	fixture := createLegacyShellTestFixture(t)
	artifacts, err := loadLegacyShellArtifacts()
	if err != nil {
		t.Fatalf("loadLegacyShellArtifacts failed: %v", err)
	}
	if err := removeLegacyShellArtifacts(artifacts); err != nil {
		t.Fatalf("removeLegacyShellArtifacts failed: %v", err)
	}
	assertLegacyWrappersRemoved(t, fixture)
	assertLegacyShellPathsRemoved(t, fixture.homeDir)
}

func createLegacyShellTestFixture(t *testing.T) legacyShellTestFixture {
	t.Helper()
	fixture := legacyShellTestFixture{homeDir: t.TempDir(), personalScript: "#!/bin/sh\necho user\n"}
	t.Setenv("HOME", fixture.homeDir)
	fixture.defaultDir = filepath.Join(fixture.homeDir, legacyWrapperDirName)
	fixture.customDir = filepath.Join(fixture.homeDir, "custom", "wrappers")
	fixture.oldToolPath = filepath.Join(fixture.defaultDir, "old-tool")
	fixture.customToolPath = filepath.Join(fixture.customDir, "custom-tool")
	fixture.personalScriptPath = filepath.Join(fixture.customDir, "personal-script")
	createLegacyTestDirectories(t, fixture.defaultDir, fixture.customDir)
	writeLegacyWrapperFixture(t, fixture.oldToolPath)
	writeLegacyWrapperFixture(t, fixture.customToolPath)
	writeLegacyWrapperFixture(t, fixture.personalScriptPath, fixture.personalScript)
	writeLegacyConfigFixture(t, fixture.homeDir, fixture.customDir)
	writeLegacyShellFixtures(t, fixture.homeDir, fixture.defaultDir, fixture.customDir)
	return fixture
}

func createLegacyTestDirectories(t *testing.T, directories ...string) {
	t.Helper()
	for _, directory := range directories {
		if err := os.MkdirAll(directory, 0o700); err != nil {
			t.Fatal(err)
		}
	}
}

func assertLegacyWrappersRemoved(t *testing.T, fixture legacyShellTestFixture) {
	t.Helper()
	assertLegacyPathMissing(t, fixture.oldToolPath)
	assertLegacyPathMissing(t, fixture.customToolPath)
	assertLegacyFile(t, fixture.personalScriptPath, fixture.personalScript)
}

func assertLegacyShellPathsRemoved(t *testing.T, home string) {
	t.Helper()
	fishConfigPath := filepath.Join(".config", "fish", "config.fish")
	shellConfigPaths := []string{".bashrc", ".zshrc", fishConfigPath}
	for _, name := range shellConfigPaths {
		path := filepath.Join(home, name)
		contents := readLegacyFile(t, path)
		hasLegacyMarker := strings.Contains(contents, legacyShellPathMark)
		preservesPersonalLine := strings.Contains(contents, "# keep this")
		shouldFail := hasLegacyMarker || !preservesPersonalLine
		if shouldFail {
			t.Fatalf("legacy cleanup changed unrelated shell config %s: %q", name, contents)
		}
	}
}

func TestLegacyWrapperRecognitionRequiresGeneratedFields(t *testing.T) {
	generated := "#!/bin/bash\n" + legacyWrapperMarker + "\nDIU_BINARY=\"diu\"\nDIU_SOCKET=\"socket\"\nDIU_TOOL=\"npm\"\nORIGINAL_BINARY=\"/bin/tool\"\n"
	if !isLegacyGeneratedWrapper(generated) {
		t.Fatal("generated wrapper was not recognized")
	}
	unrelated := "#!/bin/bash\n# Generated by DIU\necho user\n"
	if isLegacyGeneratedWrapper(unrelated) {
		t.Fatal("unrelated script was recognized as a DIU wrapper")
	}
}

func writeLegacyWrapperFixture(t *testing.T, path string, content ...string) {
	t.Helper()
	data := "#!/bin/bash\n" + legacyWrapperMarker + "\nDIU_BINARY=\"diu\"\nDIU_SOCKET=\"socket\"\nDIU_TOOL=\"npm\"\nORIGINAL_BINARY=\"/bin/tool\"\n"
	if len(content) > 0 {
		data = content[0]
	}
	fileContents := []byte(data)
	if err := os.WriteFile(path, fileContents, 0o700); err != nil {
		t.Fatal(err)
	}
}

func writeLegacyConfigFixture(t *testing.T, home, wrapperDir string) {
	t.Helper()
	path := filepath.Join(home, ".config", "diu", "config.json")
	data := fmt.Sprintf(`{"monitoring":{"process":{"wrapper_dir":%q,"auto_install_wrappers":true}}}`, wrapperDir)
	configDir := filepath.Dir(path)
	if err := os.MkdirAll(configDir, 0o700); err != nil {
		t.Fatal(err)
	}
	configContents := []byte(data)
	if err := os.WriteFile(path, configContents, 0o600); err != nil {
		t.Fatal(err)
	}
}

func writeLegacyShellFixtures(t *testing.T, home string, wrapperDirs ...string) {
	t.Helper()
	posixBlocks, fishBlocks := legacyShellPathBlocks(wrapperDirs)
	writeLegacyShellConfigFixture(t, filepath.Join(home, ".bashrc"), posixBlocks)
	writeLegacyShellConfigFixture(t, filepath.Join(home, ".zshrc"), posixBlocks)
	fishPath := filepath.Join(home, ".config", "fish", "config.fish")
	writeLegacyShellConfigFixture(t, fishPath, fishBlocks)
}

func legacyShellPathBlocks(wrapperDirs []string) ([]string, []string) {
	var posixBlocks, fishBlocks []string
	for _, dir := range wrapperDirs {
		escapedDir := escapeLegacyPath(dir)
		posixLine := fmt.Sprintf(`export PATH="%s:$PATH"`, escapedDir)
		posixBlock := legacyShellPathMark + "\n" + posixLine
		posixBlocks = append(posixBlocks, posixBlock)
		fishLine := legacyFishPathLine(dir)
		fishBlock := legacyShellPathMark + "\n" + fishLine
		fishBlocks = append(fishBlocks, fishBlock)
	}
	return posixBlocks, fishBlocks
}

func writeLegacyShellConfigFixture(t *testing.T, path string, blocks []string) {
	t.Helper()
	configDir := filepath.Dir(path)
	if err := os.MkdirAll(configDir, 0o700); err != nil {
		t.Fatal(err)
	}
	contents := "# keep this\n\n" + strings.Join(blocks, "\n\n") + "\n"
	fileContents := []byte(contents)
	if err := os.WriteFile(path, fileContents, 0o640); err != nil {
		t.Fatal(err)
	}
}

func escapeLegacyPath(path string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "`", "\\`")
	return replacer.Replace(path)
}

func readLegacyFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	contents := string(data)
	return contents
}

func assertLegacyFile(t *testing.T, path, expected string) {
	t.Helper()
	if got := readLegacyFile(t, path); got != expected {
		t.Fatalf("file contents = %q, want %q", got, expected)
	}
}

func assertLegacyPathMissing(t *testing.T, path string) {
	t.Helper()
	_, err := os.Lstat(path)
	missing := os.IsNotExist(err)
	if !missing {
		t.Fatalf("expected generated path to be absent: %s (%v)", path, err)
	}
}
