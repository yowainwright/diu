const (
	zshIntegrationGeneratedMarker = "# Generated by DIU zsh integration"
	zshSourceBlockStart           = "# >>> DIU shell integration >>>"
	zshSourceBlockEnd             = "# <<< DIU shell integration <<<"
	zshIntegrationFileName        = "shell-integration.zsh"
)

const zshPreexecHook = `_diu_load_maps() {
    if [[ ! -r "$_DIU_INTEGRATION_FILE" ]]; then
        add-zsh-hook -d preexec _diu_preexec 2>/dev/null || true
        unset _DIU_TOOL_MAP _DIU_PACKAGE_MAP _DIU_EXECUTABLE_MAP
        return 1
    fi
    typeset -gi _DIU_IN_PREEXEC=1
    source "$_DIU_INTEGRATION_FILE"
    typeset -gi _DIU_IN_PREEXEC=0
}
_diu_skip_pending_word() {
    if (( skip_exec_argument )); then skip_exec_argument=0; return 0; fi
    if (( skip_prefix_argument )); then skip_prefix_argument=0; return 0; fi
    if (( skip_redirection_target )); then skip_redirection_target=0; return 0; fi
    return 1
}
_diu_skip_redirection() {
    local word="$1" operator="${1#${1%%[!0-9]*}}"
    case "$word" in
        '>'|'>>'|'<'|'<<'|'<<<'|'<<-'|'<&'|'>&'|'<>'|'&>'|'&>>') skip_redirection_target=1; return 0 ;;
    esac
    if [[ "$word" == '&>'* || "$word" == '&>>'* || "$operator" == '>'* || "$operator" == '<'* ]]; then
        case "$operator" in
            '>'|'>>'|'<'|'<<'|'<<<'|'<<-'|'<&'|'>&'|'<>' ) skip_redirection_target=1 ;;
        esac
        return 0
    fi
    return 1
}
_diu_skip_control_header() {
    if (( loop_header )); then
        if [[ "$1" == do ]]; then loop_header=0; command_position=1; fi
        return 0
    fi
    if (( case_pattern )); then
        if [[ "$1" == ')' ]]; then case_pattern=0; command_position=1; fi
        return 0
    fi
    if (( case_header )); then
        if [[ "$1" == in ]]; then case_header=0; case_pattern=1; fi
        return 0
    fi
    return 1
}
_diu_skip_reserved_word() {
    case "$1" in
        ';'|'&&'|'||'|'|'|'|&'|'&'|'('|')'|';;'|';&'|';;&') command_position=1; command_prefix=""; command_lookup=0; exec_prefix=0; return 0 ;;
    esac
    (( command_position )) || return 1
    case "$1" in
        command|builtin|noglob|nocorrect|time|env|sudo) command_prefix="$1"; return 0 ;;
        case) case_header=1; command_position=0; return 0 ;;
        for|select) loop_header=1; command_position=0; return 0 ;;
        in|if|then|elif|else|while|until|do|!|coproc|'{') return 0 ;;
        fi|done|esac|'}') command_position=0; return 0 ;;
    esac
    return 1
}
_diu_skip_prefix_option() {
    (( command_position )) && [[ -n "$command_prefix" ]] || return 1
    if [[ "$1" == -- ]]; then command_prefix=""; return 0; fi
    case "$command_prefix:$1" in
        env:-u|env:--unset|sudo:-u|sudo:--user) skip_prefix_argument=1; return 0 ;;
        command:-*v*|command:-*V*) command_lookup=1; return 0 ;;
        command:-*|env:-*|sudo:-*|builtin:-*) return 0 ;;
    esac
    return 1
}
_diu_skip_exec_option() {
    case "$1" in
        exec) if (( command_position )); then exec_prefix=1; return 0; fi ;;
        --) if (( exec_prefix )); then exec_prefix=0; return 0; fi ;;
    esac
    if (( exec_prefix )) && [[ "$1" == -* ]]; then
        [[ "$1" == *a* ]] && skip_exec_argument=1
        return 0
    fi
    return 1
}
_diu_emit_record() {
    local timestamp_json=""
    [[ -n "$timestamp" ]] && timestamp_json=",\"timestamp\":\"$timestamp\""
    printf '{"kind":"launch_attempt","tool":%s,"command":%s%s,"packages_affected":[%s],"metadata":{"executable":%s}}\n' \
        "$1" "$3" "$timestamp_json" "$2" "$3" |
        "$diu_binary" record --background >/dev/null 2>&1 &!
}
_diu_record_command() {
    (( command_position )) && [[ "$1" != *=* ]] || return 1
    local word="${1:t}" tool package executable
    command_position=0
    exec_prefix=0
    if [[ "$command_prefix" == builtin ]] || (( command_lookup )); then
        command_prefix=""
        command_lookup=0
        return 0
    fi
    command_prefix=""
    tool="${_DIU_TOOL_MAP[$word]-}"
    [[ -n "$tool" ]] || return 0
    package="${_DIU_PACKAGE_MAP[$word]}"
    executable="${_DIU_EXECUTABLE_MAP[$word]}"
    _diu_emit_record "$tool" "$package" "$executable"
}
_diu_parse_submitted() {
    local word
    for word in ${(z)submitted}; do
        _diu_skip_pending_word "$word" && continue
        _diu_skip_redirection "$word" && continue
        _diu_skip_control_header "$word" && continue
        _diu_skip_reserved_word "$word" && continue
        _diu_skip_prefix_option "$word" && continue
        _diu_skip_exec_option "$word" && continue
        _diu_record_command "$word"
    done
}
_diu_capture_timestamp() {
    zmodload zsh/datetime 2>/dev/null || return 1
    local -a now=($epochtime)
    local formatted
    TZ=UTC0 strftime -s formatted '%Y-%m-%dT%H:%M:%S.%3.Z' "$now[1]" "$now[2]" || return 1
    timestamp="$formatted"
}
_diu_preexec() {
    local submitted="$3" diu_binary timestamp
    _diu_load_maps || return 0
    diu_binary="${commands[diu]-}"
    [[ -x "$diu_binary" ]] || return 0
    _diu_capture_timestamp || timestamp=""
    local command_position=1 command_prefix="" command_lookup=0 skip_prefix_argument=0 skip_redirection_target=0 loop_header=0 case_header=0 case_pattern=0 exec_prefix=0 skip_exec_argument=0
    _diu_parse_submitted
}
if (( ! _DIU_IN_PREEXEC )); then
    autoload -Uz add-zsh-hook
    add-zsh-hook -d preexec _diu_preexec 2>/dev/null || true
    add-zsh-hook preexec _diu_preexec
fi
`

func installZshShellIntegration(config *core.Config) error {
	if err := refreshZshShellIntegration(config); err != nil {
		return err
	}
	homeDirs, err := currentShellHomeDirs()
	if err != nil {
		return fmt.Errorf("failed to find home directory: %w", err)
	}
	return installZshSourceBlock(filepath.Join(homeDirs[0], ".zshrc"), zshIntegrationPath(config))
}

func refreshZshShellIntegration(config *core.Config) error {
	targets := discoverExecutables(config)
	path := zshIntegrationPath(config)
	contents, err := renderZshIntegration(targets, path)
	if err != nil {
		return err
	}
	if err := requireGeneratedZshIntegration(path); err != nil {
		return err
	}
	return safefs.WriteFileAtomic(path, []byte(contents), core.PrivateFileMode)
}

func requireGeneratedZshIntegration(path string) error {
	info, err := safefs.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	return validateGeneratedZshIntegration(path, info)
}

func validateGeneratedZshIntegration(path string, info os.FileInfo) error {
	if !info.Mode().IsRegular() {
		return fmt.Errorf("refusing to replace non-regular zsh integration file: %s", path)
	}
	contents, err := safefs.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !isGeneratedZshIntegration(contents) {
		return fmt.Errorf("refusing to replace unowned zsh integration file: %s", path)
	}
	return nil
}

func isGeneratedZshIntegration(contents []byte) bool {
	return strings.HasPrefix(string(contents), zshIntegrationGeneratedMarker+"\n")
}

func zshIntegrationPath(config *core.Config) string {
	return filepath.Join(config.Daemon.DataDir, zshIntegrationFileName)
}

func renderZshIntegration(targets []executableTarget, integrationPath string) (string, error) {
	var source strings.Builder
	source.WriteString(zshIntegrationGeneratedMarker + "\n")
	source.WriteString("typeset -g _DIU_INTEGRATION_FILE=" + zshSingleQuote(integrationPath) + "\n")
	source.WriteString("(( ${+_DIU_IN_PREEXEC} )) || typeset -gi _DIU_IN_PREEXEC=0\n")
	source.WriteString("typeset -gA _DIU_TOOL_MAP _DIU_PACKAGE_MAP _DIU_EXECUTABLE_MAP\n")
	source.WriteString("_DIU_TOOL_MAP=() _DIU_PACKAGE_MAP=() _DIU_EXECUTABLE_MAP=()\n")
	for _, target := range targets {
		if err := appendZshExecutableMaps(&source, target); err != nil {
			return "", err
		}
	}
	source.WriteString(zshPreexecHook)
	return source.String(), nil
}

func appendZshExecutableMaps(source *strings.Builder, target executableTarget) error {
	fields := []zshMapField{
		{mapName: "_DIU_TOOL_MAP", value: target.Tool},
		{mapName: "_DIU_PACKAGE_MAP", value: target.Package},
		{mapName: "_DIU_EXECUTABLE_MAP", value: target.Name},
	}
	for _, field := range fields {
		if err := appendZshMapEntry(source, field.mapName, target.Name, field.value); err != nil {
			return err
		}
	}
	return nil
}

type zshMapField struct {
	mapName string
	value   string
}

func appendZshMapEntry(source *strings.Builder, mapName, executableName, value string) error {
	encoded, err := json.Marshal(value)
	if err != nil {
		return fmt.Errorf("failed to encode zsh executable map: %w", err)
	}
	line := fmt.Sprintf("%s+=(%s %s)\n", mapName, zshSingleQuote(executableName), zshSingleQuote(string(encoded)))
	source.WriteString(line)
	return nil
}

func zshSingleQuote(value string) string {
	quoted := strings.ReplaceAll(value, "'", "'\\''")
	return fmt.Sprintf("'%s'", quoted)
}

func installZshSourceBlock(path, integrationPath string) error {
	content, err := readShellConfigIfPresent(path)
	if err != nil {
		return err
	}
	block := zshSourceBlock(integrationPath)
	updated, err := upsertMarkedShellBlock(string(content), block)
	if err != nil {
		return err
	}
	return writeShellConfig(path, []byte(updated))
}

func zshSourceBlock(integrationPath string) string {
	sourceLine := "source " + zshSingleQuote(integrationPath)
	return strings.Join([]string{zshSourceBlockStart, sourceLine, zshSourceBlockEnd}, "\n")
}

func upsertMarkedShellBlock(content, block string) (string, error) {
	content, err := removeMarkedShellBlocks(content)
	if err != nil {
		return "", err
	}
	hasContent := content != ""
	endsWithNewline := strings.HasSuffix(content, "\n")
	shouldAddNewline := hasContent && !endsWithNewline
	if shouldAddNewline {
		content += "\n"
	}
	hasBlankLineEnding := strings.HasSuffix(content, "\n\n")
	shouldAddBlankLine := content != "" && !hasBlankLineEnding
	if shouldAddBlankLine {
		content += "\n"
	}
	return strings.Join([]string{content, block, ""}, "\n"), nil
}

func removeZshSourceBlock() error {
	homeDirs, err := currentShellHomeDirs()
	if err != nil {
		return fmt.Errorf("failed to find home directory: %w", err)
	}
	path := filepath.Join(homeDirs[0], ".zshrc")
	return removeZshSourceBlockAt(path)
}

func removeZshSourceBlockAt(path string) error {
	content, err := readShellConfigIfPresent(path)
	if err != nil {
		return err
	}
	if content == nil {
		return nil
	}
	updated, err := removeMarkedShellBlocks(string(content))
	if err != nil {
		return err
	}
	if updated == string(content) {
		return nil
	}
	return writeShellConfig(path, []byte(updated))
}

func removeMarkedShellBlocks(content string) (string, error) {
	for strings.Contains(content, zshSourceBlockStart) || strings.Contains(content, zshSourceBlockEnd) {
		updated, err := removeOneMarkedShellBlock(content)
		if err != nil {
			return "", err
		}
		content = updated
	}
	return content, nil
}

func removeOneMarkedShellBlock(content string) (string, error) {
	start, end, err := markedShellBlockOffsets(content)
	if err != nil {
		return "", err
	}
	blockStart := shellBlockStart(content, start)
	blockEnd := shellBlockEnd(content, end)
	return joinShellConfig(content[:blockStart], content[blockEnd:]), nil
}

func markedShellBlockOffsets(content string) (int, int, error) {
	start := strings.Index(content, zshSourceBlockStart)
	end := strings.Index(content, zshSourceBlockEnd)
	if start < 0 {
		return 0, 0, fmt.Errorf("malformed DIU zsh source block")
	}
	if end < start {
		return 0, 0, fmt.Errorf("malformed DIU zsh source block")
	}
	return start, end, nil
}

func shellBlockEnd(content string, end int) int {
	blockEnd := end + len(zshSourceBlockEnd)
	if blockEnd >= len(content) {
		return blockEnd
	}
	if content[blockEnd] == '\n' {
		return blockEnd + 1
	}
	return blockEnd
}

func shellBlockStart(content string, start int) int {
	if start == 0 {
		return start
	}
	if content[start-1] == '\n' {
		return start - 1
	}
	return start
}

func joinShellConfig(prefix, suffix string) string {
	hasPrefix := prefix != ""
	hasSuffix := suffix != ""
	prefixEndsLine := strings.HasSuffix(prefix, "\n")
	suffixStartsLine := strings.HasPrefix(suffix, "\n")
	if !hasPrefix {
		return suffix
	}
	if !hasSuffix {
		return prefix
	}
	if prefixEndsLine {
		return strings.Join([]string{prefix, suffix}, "")
	}
	if suffixStartsLine {
		return strings.Join([]string{prefix, suffix}, "")
	}
	return strings.Join([]string{prefix, "\n", suffix}, "")
}

func readShellConfigIfPresent(path string) ([]byte, error) {
	target, info, err := resolveShellConfigTarget(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("failed to resolve shell config %s: %w", path, err)
	}
	if info == nil {
		return nil, nil
	}
	return readResolvedShellConfig(path, target, info)
}

func readResolvedShellConfig(path, target string, info os.FileInfo) ([]byte, error) {
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("refusing to read non-regular shell config: %s", path)
	}
	contents, err := safefs.ReadFile(target)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("failed to read shell config %s: %w", path, err)
	}
	return contents, nil
}

func writeShellConfig(path string, contents []byte) error {
	target, info, err := resolveShellConfigTarget(path)
	if os.IsNotExist(err) {
		return safefs.WriteFileAtomic(path, contents, core.PrivateFileMode)
	}
	if err != nil {
		return err
	}
	if info == nil {
		return safefs.WriteFileAtomic(path, contents, core.PrivateFileMode)
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("refusing to update non-regular shell config: %s", path)
	}
	return safefs.WriteFileAtomic(target, contents, info.Mode().Perm())
}

func resolveShellConfigTarget(path string) (string, os.FileInfo, error) {
	info, err := safefs.Lstat(path)
	if err != nil {
		return "", nil, err
	}
	if info.Mode()&os.ModeSymlink == 0 {
		return path, info, nil
	}
	target, err := filepath.EvalSymlinks(path)
	if err != nil {
		return "", nil, err
	}
	info, err = safefs.Lstat(target)
	return target, info, err
}

func removeZshShellIntegration(config *core.Config) error {
	blockErr := removeZshSourceBlock()
	fileErr := removeGeneratedZshIntegration(config)
	return errors.Join(blockErr, fileErr)
}

func removeGeneratedZshIntegration(config *core.Config) error {
	path := zshIntegrationPath(config)
	contents, err := safefs.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !isGeneratedZshIntegration(contents) {
		return nil
	}
	return os.Remove(path)
}
