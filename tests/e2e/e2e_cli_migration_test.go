//go:build e2e

package e2e

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const legacyCLIPersonalScript = "#!/bin/sh\necho keep\n"

func TestCLISetupMigratesLegacyWrappersAndShellPaths(t *testing.T) {
	f := newCLIFixture(t)
	wrapperDir := filepath.Join(f.home, "custom", "wrappers")
	addLegacyCLISetup(t, f, wrapperDir)
	setupResult := f.cli(t, "setup")
	assertCLIExit(t, setupResult, 0)
	assertLegacyCLIArtifactsRemoved(t, f, wrapperDir)
	assertCLIListenerInstalled(t, f)
}

func TestCLIUninstallRemovesLegacyWrappersAndShellPaths(t *testing.T) {
	f := newCLIFixture(t)
	f.setup(t)
	wrapperDir := filepath.Join(f.home, "custom", "wrappers")
	addLegacyCLISetup(t, f, wrapperDir)
	uninstallResult := f.cli(t, "uninstall")
	assertCLIExit(t, uninstallResult, 0)
	assertLegacyCLIArtifactsRemoved(t, f, wrapperDir)
	integrationPath := filepath.Join(f.config.Daemon.DataDir, "shell-integration.zsh")
	assertCLIMissing(t, integrationPath)
}

func addLegacyCLISetup(t *testing.T, f *cliFixture, wrapperDir string) {
	t.Helper()
	if err := os.MkdirAll(wrapperDir, 0o700); err != nil {
		t.Fatal(err)
	}
	generated := "#!/bin/bash\n# Generated by DIU\nDIU_BINARY=\"diu\"\nDIU_SOCKET=\"socket\"\nDIU_TOOL=\"homebrew\"\nORIGINAL_BINARY=\"/bin/tool\"\n"
	generatedPath := filepath.Join(wrapperDir, "legacy-tool")
	writeCLIFile(t, generatedPath, generated, 0o700)
	personalPath := filepath.Join(wrapperDir, "personal-script")
	writeCLIFile(t, personalPath, legacyCLIPersonalScript, 0o700)
	injectLegacyCLIConfig(t, f, wrapperDir)
	posixLine := fmt.Sprintf(`export PATH="%s:$PATH"`, wrapperDir)
	fishLine := fmt.Sprintf("if not contains \"%s\" $PATH\n    set -gx PATH \"%s\" $PATH\nend", wrapperDir, wrapperDir)
	bashrc := filepath.Join(f.home, ".bashrc")
	zshrc := filepath.Join(f.home, ".zshrc")
	fishConfig := filepath.Join(f.home, ".config", "fish", "config.fish")
	appendLegacyCLIBlock(t, bashrc, posixLine)
	appendLegacyCLIBlock(t, zshrc, posixLine)
	appendLegacyCLIBlock(t, fishConfig, fishLine)
}

func injectLegacyCLIConfig(t *testing.T, f *cliFixture, wrapperDir string) {
	t.Helper()
	path := filepath.Join(f.home, ".config", "diu", "config.json")
	var config map[string]any
	contents := readCLIFile(t, path)
	configData := []byte(contents)
	if err := json.Unmarshal(configData, &config); err != nil {
		t.Fatal(err)
	}
	monitoringValue := config["monitoring"]
	monitoring, ok := monitoringValue.(map[string]any)
	if !ok {
		t.Fatal("monitoring config has an unexpected shape")
	}
	process := make(map[string]any)
	process["wrapper_dir"] = wrapperDir
	process["auto_install_wrappers"] = true
	monitoring["process"] = process
	updated, err := json.Marshal(config)
	if err != nil {
		t.Fatal(err)
	}
	updatedContents := string(updated)
	writeCLIFile(t, path, updatedContents, 0o600)
}

func appendLegacyCLIBlock(t *testing.T, path, line string) {
	t.Helper()
	contents := readCLIFile(t, path)
	block := "# DIU path configuration\n" + line + "\n"
	updated := contents + "\n" + block
	writeCLIFile(t, path, updated, 0o640)
}

func assertLegacyCLIArtifactsRemoved(t *testing.T, f *cliFixture, wrapperDir string) {
	t.Helper()
	generatedPath := filepath.Join(wrapperDir, "legacy-tool")
	personalPath := filepath.Join(wrapperDir, "personal-script")
	assertCLIMissing(t, generatedPath)
	assertCLIFile(t, personalPath, legacyCLIPersonalScript)
	legacyShellFiles := []string{".bashrc", ".zshrc", ".config/fish/config.fish"}
	for _, name := range legacyShellFiles {
		path := filepath.Join(f.home, name)
		contents := readCLIFile(t, path)
		if strings.Contains(contents, "# DIU path configuration") {
			t.Fatalf("legacy PATH block remains in %s: %q", name, contents)
		}
	}
}
