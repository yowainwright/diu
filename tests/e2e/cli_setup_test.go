func TestCLISetupIsRepeatableAndInstallsZshListener(t *testing.T) {
	f := newCLIFixture(t)
	before := snapshotCLIHome(t, f.home)
	for range 2 {
		f.setup(t)
		assertCLIListenerInstalled(t, f)
	}
	assertCLIChanges(t, before, snapshotCLIHome(t, f.home))
}

func assertCLIListenerInstalled(t *testing.T, f *cliFixture) {
	t.Helper()
	zshrc := readCLIFile(t, filepath.Join(f.home, ".zshrc"))
	if strings.Count(zshrc, "# >>> DIU shell integration >>>") != 1 {
		t.Fatalf("zshrc does not contain one DIU source block: %q", zshrc)
	}
	integration := filepath.Join(f.config.Daemon.DataDir, "shell-integration.zsh")
	if !strings.Contains(zshrc, "source '"+integration+"'") {
		t.Fatalf("zshrc does not source %q: %q", integration, zshrc)
	}
	contents := readCLIFile(t, integration)
	for _, expected := range []string{"# Generated by DIU zsh integration", "_DIU_TOOL_MAP+=('probe' '\"homebrew\"')", "record --background"} {
		if !strings.Contains(contents, expected) {
			t.Fatalf("listener is missing %q: %s", expected, contents)
		}
	}
	assertCLIFile(t, filepath.Join(f.home, ".bashrc"), shellSentinel)
	assertCLIFile(t, filepath.Join(f.home, ".config/fish/config.fish"), shellSentinel)
}

func TestCLISetupDoesNotChangeShellsOutsideZsh(t *testing.T) {
	f := newCLIFixture(t)
	f.setup(t)
	for _, name := range []string{".bashrc", ".config/fish/config.fish"} {
		assertCLIFile(t, filepath.Join(f.home, name), shellSentinel)
	}
}

func TestCLISetupRemovesLegacyWrapperIntegration(t *testing.T) {
	f := newCLIFixture(t)
	wrapperDir := filepath.Join(f.home, ".local", "bin", "diu-wrappers")
	generatedWrapper := filepath.Join(wrapperDir, "probe")
	writeCLIFile(t, generatedWrapper, "#!/bin/bash\n# Generated by DIU\nDIU_BINARY=\"diu\"\nDIU_SOCKET=\"/tmp/diu.sock\"\nORIGINAL_BINARY=\"/usr/bin/probe\"\nDIU_TOOL=\"homebrew\"\n", 0o700)
	userWrapper := filepath.Join(wrapperDir, "personal-tool")
	writeCLIFile(t, userWrapper, "#!/bin/sh\necho user-owned\n", 0o700)
	writeLegacyCLIPathBlocks(t, f.home, wrapperDir)

	f.setup(t)
	assertCLIMissing(t, generatedWrapper)
	assertCLIFile(t, userWrapper, "#!/bin/sh\necho user-owned\n")
	for _, path := range shellFiles {
		contents := readCLIFile(t, filepath.Join(f.home, path))
		if strings.Contains(contents, "# DIU path configuration") {
			t.Fatalf("legacy PATH block remains in %s: %q", path, contents)
		}
	}
	assertCLIListenerInstalled(t, f)
}

func writeLegacyCLIPathBlocks(t *testing.T, home, wrapperDir string) {
	t.Helper()
	posixLine := "export PATH=\"" + wrapperDir + ":$PATH\""
	fishLine := "if not contains \"" + wrapperDir + "\" $PATH\n    set -gx PATH \"" + wrapperDir + "\" $PATH\nend"
	for _, entry := range []struct {
		path string
		line string
	}{
		{path: filepath.Join(home, ".bashrc"), line: posixLine},
		{path: filepath.Join(home, ".zshrc"), line: posixLine},
		{path: filepath.Join(home, ".config", "fish", "config.fish"), line: fishLine},
	} {
		writeCLIFile(t, entry.path, shellSentinel+"# DIU path configuration\n"+entry.line+"\n", 0o640)
	}
}

type cliFileState struct {
	content string
	mode    os.FileMode
}

func snapshotCLIHome(t *testing.T, home string) map[string]cliFileState {
	t.Helper()
	files := make(map[string]cliFileState)
	err := filepath.WalkDir(home, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name, err := filepath.Rel(home, path)
		if err != nil {
			return err
		}
		files[name] = snapshotCLIEntry(t, path, entry)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func snapshotCLIEntry(t *testing.T, path string, entry os.DirEntry) cliFileState {
	t.Helper()
	info, err := entry.Info()
	if err != nil {
		t.Fatal(err)
	}
	state := cliFileState{mode: info.Mode()}
	if info.Mode().IsRegular() {
		state.content = readCLIFile(t, path)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		state.content, err = os.Readlink(path)
		if err != nil {
			t.Fatal(err)
		}
	}
	return state
}

func assertCLIChanges(t *testing.T, before, after map[string]cliFileState) {
	t.Helper()
	for path, state := range after {
		if !allowedCLISetupChange(path) && before[path] != state {
			t.Errorf("setup changed an unrelated file: %s", path)
		}
	}
	for path := range before {
		if _, exists := after[path]; !exists {
			t.Errorf("setup removed an unrelated file: %s", path)
		}
	}
}

func allowedCLISetupChange(path string) bool {
	for _, name := range shellFiles {
		if path == name {
			return true
		}
	}
	if path == ".config/diu/config.json" || path == ".local" || path == ".local/share" || path == ".local/share/diu" {
		return true
	}
	return strings.HasPrefix(path, ".local/share/diu/")
}

func assertCLICleanShells(t *testing.T, f *cliFixture) {
	t.Helper()
	for _, name := range shellFiles {
		path := filepath.Join(f.home, name)
		want := shellSentinel
		if name == ".zshrc" {
			want += "\n"
		}
		assertCLIFile(t, path, want)
		info, err := os.Stat(path)
		if err != nil || info.Mode().Perm() != 0o640 {
			t.Fatalf("cleanup changed shell permissions: %s: %v, %v", name, info, err)
		}
	}
	assertCLIFile(t, filepath.Join(f.home, ".zprofile"), shellSentinel)
}
